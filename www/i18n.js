let LANG = "en";
let PR = new Intl.PluralRules("en");

/** ?lang= wins, then a saved choice, then the browser, then English. */
function pickLang(saved) {
  const q = new URLSearchParams(location.search).get("lang");
  const codes = LANGS.map((l) => l.code);
  const want = [q, saved, ...(navigator.languages || [navigator.language || ""])];
  for (const w of want) {
    if (!w) continue;
    const base = String(w).toLowerCase().split("-")[0];
    if (codes.includes(base)) return base;
  }
  return "en";
}

function setLang(code) {
  LANG = DICT[code] ? code : "en";
  try { PR = new Intl.PluralRules(LANG); } catch { PR = new Intl.PluralRules("en"); }
  const rtl = RTL.has(LANG);
  document.documentElement.lang = LANG;
  document.documentElement.dir = rtl ? "rtl" : "ltr";
  return LANG;
}

const isRTL = () => RTL.has(LANG);

function fill(s, vars) {
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : s;
}

/** Translate. Falls back to English, then to the key itself, so a missing
 * string shows up as a visible bug rather than as blank space. */
function t(key, vars) {
  const s = (DICT[LANG] && DICT[LANG][key]) ?? DICT.en[key] ?? key;
  return fill(s, vars);
}

/** Plural form via Intl, which knows that Russian has four and Arabic six. */
function tn(key, n, vars) {
  const cat = PR.select(n);
  const d = DICT[LANG] || {};
  const s = d[`${key}.${cat}`] ?? d[`${key}.other`] ?? d[`${key}.one`]
         ?? DICT.en[`${key}.${cat}`] ?? DICT.en[`${key}.other`] ?? key;
  return fill(s, Object.assign({ n: fmtNum(n) }, vars));
}

const fmtNum = (n) => { try { return new Intl.NumberFormat(LANG).format(n); } catch { return String(n); } };

/** Relative time, localised. */
function tAgo(ts) {
  if (!ts) return "";
  const m = Math.round((Date.now() - ts) / 60000);
  if (m < 1) return t("time.now");
  if (m < 60) return t("time.m", { n: fmtNum(m) });
  if (m < 1440) return t("time.h", { n: fmtNum(Math.round(m / 60)) });
  return t("time.d", { n: fmtNum(Math.round(m / 1440)) });
}

/** A localised list: "location, data and systems". */
function tList(items) {
  try { return new Intl.ListFormat(LANG, { style: "long", type: "conjunction" }).format(items); }
  catch { return items.join(", "); }
}

const tCat = (c) => t(`cat.${c}`);
const tSev = (s) => t(`sev.${s}`);

/** Why an action needs discernment, phrased locally. Horizon sends structured
 * risk and the appetite it was measured against; the English sentence it also
 * sends is the last resort, not the source. */
function tWhy(entry, appetite, fallback) {
  const out = [];
  if (entry.severity === "SEVERE") out.push(t("why.severe"));
  if (entry.discernment === "always") out.push(t("why.always"));
  for (const [c, got] of Object.entries(entry.risk || {})) {
    const want = (appetite && appetite[c]) || "LOW";
    if (SEVORD[got] > SEVORD[want]) out.push(t("why.above", { cat: tCat(c), got: tSev(got), want: tSev(want) }));
  }
  if (out.length) return out;
  return fallback && fallback.length ? [String(fallback[0])] : [t("why.within")];
}

window.I18N = { LANGS, DICT, setLang, pickLang, t, tn, tAgo, tList, tCat, tSev, tWhy, isRTL, fmtNum,
  get lang() { return LANG; } };

